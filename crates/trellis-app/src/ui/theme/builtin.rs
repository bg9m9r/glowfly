//! The built-in palettes. DARK and LIGHT are the standard Trellis themes: the icon's lattice
//! green as the accent, sand tags, and neutrals tinted green (Dark) or warm paper (Light). The
//! high-contrast and Sand palettes are in `builtin_extra.rs`. The values and the rules they meet
//! are in docs/COLOUR.md.

use super::color::Palette;
use super::families::{Attention, BRANCH, Repository, Status};
use eframe::egui::Color32;
use trellis_core::settings::BuiltinTheme;

pub use super::builtin_extra::{HIGH_CONTRAST_DARK, HIGH_CONTRAST_LIGHT, SAND};

const fn rgb(r: u8, g: u8, b: u8) -> Color32 {
    Color32::from_rgb(r, g, b)
}

/// The palette of a built-in theme.
pub fn builtin(t: BuiltinTheme) -> &'static Palette {
    match t {
        BuiltinTheme::Dark => &DARK,
        BuiltinTheme::Light => &LIGHT,
        BuiltinTheme::HighContrastDark => &HIGH_CONTRAST_DARK,
        BuiltinTheme::HighContrastLight => &HIGH_CONTRAST_LIGHT,
        BuiltinTheme::Sand => &SAND,
    }
}

